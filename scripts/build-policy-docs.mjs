#!/usr/bin/env node
/**
 * Turn the three policy documents into a module the app can render — `E20-38`.
 *
 *     node scripts/build-policy-docs.mjs          # write
 *     node scripts/build-policy-docs.mjs --check  # fail if the written file is stale
 *
 * ## Why generated rather than written twice
 *
 * `docs/privacy-policy.md`, `docs/terms.md` and `docs/refund-policy.md` are the documents that
 * go to the lawyer (`E20-01`) and get published. If the app carried its own copy there would be
 * **two texts and one of them would be wrong**, and the one on the parent's phone is the one
 * that matters legally. So the app carries a build artefact of the same file, and `--check`
 * runs in the smoke test so the artefact cannot drift from its source.
 *
 * ## The `«…-PENDING-…»` flag travels with the text
 *
 * All three still contain placeholder tokens awaiting `E20-01`. That is recorded per document
 * as `hasPendingTokens`, so the app can say plainly that a document is not final rather than
 * showing a parent a policy with `«GRIEVANCE-OFFICER-NAME-PENDING-E20-21»` in it — and so
 * `E20-27`'s production guard has something to assert against.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'packages', 'shared', 'src', 'policy', 'documents.generated.ts');

/** The three documents Account links to, in the order they are listed there. */
const DOCUMENTS = [
  { key: 'privacy', title: 'Privacy policy', file: 'docs/privacy-policy.md' },
  { key: 'terms', title: 'Terms of use', file: 'docs/terms.md' },
  { key: 'refund', title: 'Refund policy', file: 'docs/refund-policy.md' },
];

/** `«ANYTHING-PENDING-E20-01»` — the repo-wide convention for an unresolved value. */
const PENDING = /«[^»]*PENDING[^»]*»/g;

/**
 * Strip the YAML frontmatter. It is repo metadata (`title:`, `status:`) and means nothing to a
 * parent; leaving it in would render three lines of `---` at the top of a legal document.
 */
function body(text) {
  return text.startsWith('---') ? text.replace(/^---[\s\S]*?\n---\n/, '').trimStart() : text;
}

function generate() {
  const docs = DOCUMENTS.map((d) => {
    const markdown = body(readFileSync(join(ROOT, d.file), 'utf8'));
    const pending = [...new Set(markdown.match(PENDING) ?? [])].sort();
    return { ...d, markdown, pending };
  });

  const entries = docs
    .map(
      (d) => `  ${d.key}: {
    title: ${JSON.stringify(d.title)},
    source: ${JSON.stringify(d.file)},
    hasPendingTokens: ${d.pending.length > 0},
    pendingTokens: ${JSON.stringify(d.pending)},
    markdown: ${JSON.stringify(d.markdown)},
  },`,
    )
    .join('\n');

  return `// GENERATED by scripts/build-policy-docs.mjs — do not edit.
//
// Source of truth is docs/{privacy-policy,terms,refund-policy}.md. Edit those, then run the
// script. \`npm run check:policy-docs\` fails if this file is stale, so the text on a parent's
// phone cannot drift from the text that went to the lawyer.
//
// \`E20-38\`. The \`pendingTokens\` are the «…-PENDING-…» placeholders still awaiting \`E20-01\`;
// \`E20-27\` is the guard that stops a document carrying one from reaching a production build.

/** One published policy document, as the app renders it. */
export interface PolicyDocument {
  title: string;
  /** The markdown file this came from, so a reader can find the original. */
  source: string;
  /** True while the document still contains an unresolved «…-PENDING-…» placeholder. */
  hasPendingTokens: boolean;
  pendingTokens: string[];
  markdown: string;
}

export type PolicyKey = ${DOCUMENTS.map((d) => `'${d.key}'`).join(' | ')};

export const POLICY_DOCUMENTS: Record<PolicyKey, PolicyDocument> = {
${entries}
};
`;
}

const next = generate();
mkdirSync(dirname(OUT), { recursive: true });

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (current !== next) {
    console.error(
      'packages/shared/src/policy/documents.generated.ts is stale.\n' +
        'A policy document changed and the app still carries the old text. Run:\n' +
        '  node scripts/build-policy-docs.mjs',
    );
    process.exit(1);
  }
  console.log('policy documents are in sync.');
} else {
  writeFileSync(OUT, next);
  console.log(`policy documents written — ${DOCUMENTS.length} documents.`);
}
