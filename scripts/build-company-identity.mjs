#!/usr/bin/env node
/**
 * Turn `docs/legal/company.json` into a module the app can bundle — `E12-30`.
 *
 *     node scripts/build-company-identity.mjs          # write
 *     node scripts/build-company-identity.mjs --check  # fail if the written file is stale
 *
 * ## Why this exists, and it is not a style preference
 *
 * `packages/shared/src/legal/company.ts` imported `docs/legal/company.json` directly, four
 * directories up and outside every workspace. That works on a laptop and **cannot work on an EAS
 * build worker**: `.easignore` excludes `docs/` deliberately — 1.25 MB of prose on a 85 KB/s
 * upload — while `packages/` is uploaded because the app genuinely depends on it. So the mobile
 * bundle reached into a directory that was not there and iOS died in the eager-bundle phase with
 *
 *     Unable to resolve module ../../../../docs/legal/company.json
 *
 * surfaced by the CLI as nothing but "Unknown error. See logs of the Bundle JavaScript build
 * phase." `.easignore`'s own header records the identical failure for `config/`, which "cost
 * three builds" — this is the second instance of one lesson.
 *
 * ## Why generate rather than move the JSON
 *
 * `docs/legal/company.json` is the source of entity facts and is read by the web app, the invoice
 * renderer and `sync-seller-identity.mjs`. Moving it under `packages/` to satisfy a bundler would
 * put a legal document inside a code package and break three other readers.
 *
 * `build-policy-docs.mjs` already solved exactly this for the policy documents, for exactly this
 * reason. Same shape, same `--check` in the smoke test so the artefact cannot drift from source.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'docs', 'legal', 'company.json');
const OUT = join(ROOT, 'packages', 'shared', 'src', 'legal', 'company.generated.ts');

function generate() {
  // Parsed and re-serialised rather than inlined verbatim: it proves the source is valid JSON at
  // build time rather than at the first import, and it strips any comment keys from the output.
  const data = JSON.parse(readFileSync(SRC, 'utf8'));
  return (
    `// GENERATED by scripts/build-company-identity.mjs from docs/legal/company.json.\n` +
    `// Do not edit. Change the JSON and re-run; \`--check\` runs in the smoke test.\n` +
    `//\n` +
    `// It exists because the app cannot import from docs/ — .easignore excludes that directory\n` +
    `// from the EAS upload, and the mobile bundle died resolving it. See the script header.\n` +
    `export const COMPANY_JSON = ${JSON.stringify(data, null, 2)} as const;\n`
  );
}

const next = generate();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (current !== next) {
    console.error(
      'company.generated.ts is stale. Run `node scripts/build-company-identity.mjs` and commit.',
    );
    process.exit(1);
  }
  console.log('company identity artefact is current.');
} else {
  writeFileSync(OUT, next);
  console.log('company.generated.ts written from docs/legal/company.json.');
}
